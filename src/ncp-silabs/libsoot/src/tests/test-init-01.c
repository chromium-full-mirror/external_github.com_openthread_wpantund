#ifndef ASSERT_REQUIRE_FAILURE_HOOK
#define ASSERT_REQUIRE_FAILURE_HOOK     abort()
#endif

#include "test-harness.h"

int
main(void)
{
	BEGIN_TEST();

	REQUIRE_NOT_CONNECTED();

	VERIFY_NEXT_TIMEOUT(CMS_DISTANT_FUTURE);

	REQUIRE_WRITE_BLOCKED();

	INCREMENT_TIME_MS(100);

	VERIFY_NEXT_TIMEOUT(CMS_DISTANT_FUTURE);

	VERIFY_TX_PACKET(SOOT_PACKET_TYPE_RESET,1,0,{});

	VERIFY_NEXT_TIMEOUT(SOOT_ACK_TIMEOUT_MS);

	PROCESS_RX_PACKET(SOOT_PACKET_TYPE_RSTACK,1,1,{});

	PROCESS_RX_PACKET(SOOT_PACKET_TYPE_RESET,1,1,{});

	VERIFY_TX_PACKET(SOOT_PACKET_TYPE_RSTACK,1,1,{});

	REQUIRE_CONNECTED();

	REQUIRE_EMPTY_TX();

	END_TEST();
}
